export function articleText(
  article: DemoArticle,
  index: number,
  material: ShowcaseMaterial,
): Block[] {
  const rest = article.showcase
    ? SHOWCASE_TEXTS[article.showcase](material)
    : STANDARD_SECTIONS[article.category][index % 2];
  return [paragraph(article.lead), ...rest];
}
